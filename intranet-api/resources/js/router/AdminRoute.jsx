import React from "react";

import {
    Navigate
} from "react-router-dom";

export default function AdminRoute({
    children
}) {

    /*
    |--------------------------------------------------------------------------
    | TOKEN
    |--------------------------------------------------------------------------
    */

    const token =
        localStorage.getItem("token");

    /*
    |--------------------------------------------------------------------------
    | USER
    |--------------------------------------------------------------------------
    */

    const user = JSON.parse(
        localStorage.getItem("user")
    );

    /*
    |--------------------------------------------------------------------------
    | NO LOGIN
    |--------------------------------------------------------------------------
    */

    if (!token) {

        return <Navigate to="/" />;
    }

    /*
    |--------------------------------------------------------------------------
    | NO ADMIN
    |--------------------------------------------------------------------------
    */

    if (
        !user ||
        user.role !== "admin"
    ) {

        return (
            <Navigate to="/dashboard" />
        );
    }

    /*
    |--------------------------------------------------------------------------
    | ADMIN OK
    |--------------------------------------------------------------------------
    */

    return children;
}